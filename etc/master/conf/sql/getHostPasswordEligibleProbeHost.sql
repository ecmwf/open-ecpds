SELECT H.HOS_HOST,H.HOS_LOGIN,H.HOS_DIR,H.TME_NAME,A.DES_NAME,D.DES_ACTIVE,
  E.ECM_CLASSE,E.ECM_ARCHIVE,M.TME_VALUE,H.HOS_DATA,E.ECM_NAME
FROM HOST H JOIN TRANSFER_METHOD M ON M.TME_NAME=H.TME_NAME
  JOIN ECTRANS_MODULE E ON E.ECM_NAME=M.ECM_NAME
  JOIN ASSOCIATION A ON A.HOS_NAME=H.HOS_NAME
  JOIN DESTINATION D ON D.DES_NAME=A.DES_NAME
WHERE H.HOS_NAME=:host AND H.HOS_ACTIVE=1 AND H.HOS_TYPE='Dissemination'
  AND COALESCE(H.HOS_AUTOMATIC_LOCATION,0)=0
  AND H.HOS_DIR IS NOT NULL
  AND M.TME_ACTIVE=1 AND M.TME_RESTRICT=0 AND M.TME_RESOLVE=1
  AND E.ECM_ACTIVE=1
LIMIT 2 FOR UPDATE
