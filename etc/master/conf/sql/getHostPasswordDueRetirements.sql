#menu "ECpdsBase"
#name "getHostPasswordDueRetirements"
#group "select"
#timeout "5"
SELECT A.HOS_NAME,A.HPA_PREVIOUS_REF,A.HPA_ACTIVE_REF FROM HOST_PASSWORD_ACTIVE A
JOIN HOST_PASSWORD_ACTIVATION S ON S.HPA_REF=A.HPA_ACTIVE_REF
WHERE A.HPA_PREVIOUS_REF IS NOT NULL AND S.HPA_FIRST_SUCCESS_AT IS NOT NULL
  AND S.HPA_RETIRE_GRACE_SECONDS BETWEEN 3600 AND 2592000
  AND TIMESTAMPADD(SECOND,S.HPA_RETIRE_GRACE_SECONDS,S.HPA_FIRST_SUCCESS_AT)<=CURRENT_TIMESTAMP(6)
ORDER BY S.HPA_FIRST_SUCCESS_AT LIMIT 16
