CREATE TABLE IF NOT EXISTS STORAGE_LIFECYCLE (
  DAF_ID decimal(10,0) NOT NULL,
  SLC_INSTANCE int NOT NULL DEFAULT 0,
  SLC_PIN_UNTIL bigint NOT NULL DEFAULT 0,
  SLC_PIN_REASON varchar(512) NOT NULL DEFAULT '',
  SLC_PIN_BY varchar(64) NOT NULL DEFAULT '',
  SLC_STATE varchar(32) NOT NULL DEFAULT 'FULL',
  SLC_MESSAGE varchar(1024) NOT NULL DEFAULT '',
  SLC_POLICIES varchar(2048) NOT NULL DEFAULT '',
  SLC_ELIGIBLE_AT bigint NOT NULL DEFAULT 0,
  SLC_GUARANTEED_UNTIL bigint NOT NULL DEFAULT 0,
  SLC_EVALUATED_AT bigint NOT NULL DEFAULT 0,
  SLC_REDUCED_AT bigint NOT NULL DEFAULT 0,
  SLC_RECLAIMABLE_BYTES bigint NOT NULL DEFAULT 0,
  SLC_RECLAIMED_BYTES bigint NOT NULL DEFAULT 0,
  SLC_REPLICAS_DROPPED bigint NOT NULL DEFAULT 0,
  PRIMARY KEY (DAF_ID),
  CONSTRAINT STORAGE_LIFECYCLE_FILE_FK FOREIGN KEY (DAF_ID) REFERENCES DATA_FILE (DAF_ID) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;

